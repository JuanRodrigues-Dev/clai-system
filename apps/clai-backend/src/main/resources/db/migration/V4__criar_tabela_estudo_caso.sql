CREATE TABLE estudo_caso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id UUID NOT NULL,
    data_realizacao DATE NOT NULL,
    participantes TEXT NOT NULL,
    historico_escolar TEXT,
    historico_familiar TEXT,
    barreiras_dificuldades TEXT,
    potencialidades TEXT,
    necessidades_suporte TEXT,
    necessita_acompanhamento BOOLEAN NOT NULL DEFAULT FALSE,
    necessita_adaptacao_curricular BOOLEAN NOT NULL DEFAULT FALSE,
    conclusoes TEXT,
    encaminhamentos TEXT,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_estudo_caso_aluno FOREIGN KEY (aluno_id) REFERENCES aluno (id) ON DELETE CASCADE,
    CONSTRAINT uk_estudo_caso_aluno UNIQUE (aluno_id)
);
