CREATE TABLE pei (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acompanhamento_id BIGINT NOT NULL,
    diagnostico_pedagogico TEXT NOT NULL,
    recursos_tecnologia_assistiva TEXT,
    status VARCHAR(50) NOT NULL DEFAULT 'EM_ELABORACAO',
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pei_acompanhamento FOREIGN KEY (acompanhamento_id) REFERENCES acompanhamento (id) ON DELETE CASCADE,
    CONSTRAINT uk_pei_acompanhamento UNIQUE (acompanhamento_id),
    CONSTRAINT ck_pei_status CHECK (status IN ('EM_ELABORACAO', 'AGUARDANDO_ASSINATURAS', 'HOMOLOGADO'))
);

CREATE TABLE pea_disciplina (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pei_id BIGINT NOT NULL,
    disciplina_id BIGINT NOT NULL,
    nome_professor VARCHAR(160) NOT NULL,
    adaptacoes_metodologicas TEXT NOT NULL,
    criterios_avaliacao TEXT NOT NULL,
    observacoes TEXT,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pea_disciplina_pei FOREIGN KEY (pei_id) REFERENCES pei (id) ON DELETE CASCADE,
    CONSTRAINT fk_pea_disciplina_disciplina FOREIGN KEY (disciplina_id) REFERENCES disciplina (id)
);

CREATE INDEX idx_pea_disciplina_pei ON pea_disciplina (pei_id);
CREATE INDEX idx_pea_disciplina_disciplina ON pea_disciplina (disciplina_id);
