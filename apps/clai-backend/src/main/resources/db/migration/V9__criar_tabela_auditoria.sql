CREATE TABLE auditoria_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    usuario_email VARCHAR(255) NOT NULL,
    acao VARCHAR(50) NOT NULL,
    recurso VARCHAR(50) NOT NULL,
    identificador_recurso VARCHAR(100),
    ip_origem VARCHAR(50),
    detalhes TEXT
);

CREATE INDEX idx_auditoria_log_timestamp ON auditoria_log (timestamp DESC);
CREATE INDEX idx_auditoria_log_usuario_email ON auditoria_log (usuario_email);
CREATE INDEX idx_auditoria_log_recurso ON auditoria_log (recurso);
