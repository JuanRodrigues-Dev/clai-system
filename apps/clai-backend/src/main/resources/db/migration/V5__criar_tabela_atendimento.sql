CREATE TABLE atendimento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acompanhamento_id BIGINT NOT NULL,
    data_atendimento DATE NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fim TIME NOT NULL,
    modalidade_local VARCHAR(200),
    tipo VARCHAR(150),
    profissionais TEXT,
    participantes TEXT,
    demanda TEXT,
    descricao TEXT,
    resultado TEXT,
    encaminhamentos TEXT,
    observacoes TEXT,
    proximo_atendimento DATE,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_atendimento_acompanhamento
        FOREIGN KEY (acompanhamento_id)
        REFERENCES acompanhamento (id)
        ON DELETE CASCADE
);

CREATE INDEX idx_atendimento_acompanhamento_data
    ON atendimento (acompanhamento_id, data_atendimento DESC, hora_inicio DESC);
