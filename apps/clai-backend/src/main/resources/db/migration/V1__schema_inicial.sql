CREATE TABLE usuarios (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          email VARCHAR(180) NOT NULL,
                          senha_hash VARCHAR(255) NOT NULL,
                          ativo BOOLEAN NOT NULL DEFAULT TRUE,
                          criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          CONSTRAINT uk_usuarios_email UNIQUE (email)
);

CREATE TABLE roles (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       nome VARCHAR(60) NOT NULL,
                       descricao VARCHAR(255),
                       CONSTRAINT uk_roles_nome UNIQUE (nome)
);

CREATE TABLE users_roles (
                             usuario_id BIGINT NOT NULL,
                             role_id BIGINT NOT NULL,
                             PRIMARY KEY (usuario_id, role_id),
                             CONSTRAINT fk_users_roles_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE,
                             CONSTRAINT fk_users_roles_role FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE CASCADE
);

CREATE TABLE cursos (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        nome VARCHAR(160) NOT NULL,
                        nivel VARCHAR(60) NOT NULL,
                        ativo BOOLEAN NOT NULL DEFAULT TRUE,
                        criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                        CONSTRAINT uk_cursos_nome UNIQUE (nome)
);

CREATE TABLE disciplinas (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             nome VARCHAR(160) NOT NULL,
                             codigo VARCHAR(40),
                             periodo INTEGER,
                             carga_horaria INTEGER,
                             curso_id BIGINT NOT NULL,
                             ativo BOOLEAN NOT NULL DEFAULT TRUE,
                             criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                             CONSTRAINT fk_disciplinas_curso FOREIGN KEY (curso_id) REFERENCES cursos (id),
                             CONSTRAINT uk_disciplinas_nome_curso UNIQUE (nome, curso_id)
);

CREATE TABLE alunos (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        nome VARCHAR(160) NOT NULL,
                        matricula VARCHAR(50) NOT NULL,
                        curso VARCHAR(120) NOT NULL,
                        periodo INTEGER NOT NULL,
                        email VARCHAR(160),
                        telefone VARCHAR(20),
                        ativo BOOLEAN NOT NULL DEFAULT TRUE,
                        CONSTRAINT uk_alunos_matricula UNIQUE (matricula)
);