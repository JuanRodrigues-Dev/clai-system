CREATE TABLE usuario (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         email VARCHAR(255) NOT NULL,
                         senha_hash VARCHAR(255) NOT NULL,
                         criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                         ativo BOOLEAN NOT NULL DEFAULT TRUE,
                         CONSTRAINT uk_usuario_email UNIQUE (email)
);

CREATE TABLE roles (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       nome VARCHAR(60) NOT NULL,
                       descricao VARCHAR(255),
                       CONSTRAINT uk_roles_nome UNIQUE (nome)
);

CREATE TABLE users_roles (
                             usuario_id BIGINT NOT NULL,
                             role_id BIGINT NOT NULL,
                             PRIMARY KEY (usuario_id, role_id),
                             CONSTRAINT fk_users_roles_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE,
                             CONSTRAINT fk_users_roles_role FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE CASCADE
);

CREATE TABLE curso (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       nome VARCHAR(160) NOT NULL,
                       nivel VARCHAR(60) NOT NULL,
                       ativo BOOLEAN NOT NULL DEFAULT TRUE,
                       criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       CONSTRAINT uk_curso_nome UNIQUE (nome)
);

CREATE TABLE disciplina (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            nome VARCHAR(160) NOT NULL,
                            codigo VARCHAR(40),
                            periodo INTEGER,
                            carga_horaria INTEGER,
                            curso_id BIGINT NOT NULL,
                            ativo BOOLEAN NOT NULL DEFAULT TRUE,
                            criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                            CONSTRAINT fk_disciplina_curso FOREIGN KEY (curso_id) REFERENCES curso (id),
                            CONSTRAINT uk_disciplina_nome_curso UNIQUE (nome, curso_id)
);

CREATE TABLE aluno (
                       id UUID PRIMARY KEY,
                       matricula VARCHAR(50) NOT NULL,
                       nome VARCHAR(255) NOT NULL,
                       curso VARCHAR(255) NOT NULL,
                       origem_identificacao VARCHAR(100) NOT NULL,
                       dt_criacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       ativo BOOLEAN NOT NULL DEFAULT TRUE,
                       CONSTRAINT uk_aluno_matricula UNIQUE (matricula)
);