CREATE TABLE acompanhamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id UUID NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'EM_ANDAMENTO',
    data_inicio DATE NOT NULL DEFAULT CURRENT_DATE,
    frequencia VARCHAR(120) NOT NULL,
    profissionais_responsaveis VARCHAR(500) NOT NULL,
    objetivos VARCHAR(2000) NOT NULL,
    observacoes VARCHAR(2000),
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_acompanhamento_aluno FOREIGN KEY (aluno_id) REFERENCES aluno (id) ON DELETE CASCADE,
    CONSTRAINT uk_acompanhamento_aluno UNIQUE (aluno_id),
    CONSTRAINT ck_acompanhamento_status CHECK (status IN ('EM_ANDAMENTO', 'PAUSADO', 'ALTA', 'CONCLUIDO', 'EVASAO'))
);
